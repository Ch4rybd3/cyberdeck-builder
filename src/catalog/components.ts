// The open build's own parts. Every derived function (geometry, power, ports,
// checks, BOM) syncs this from the build it is given, and the build store
// syncs it on every change, so lookups by id resolve custom parts too.
let custom = new Map<string, CatalogComponent>()

export function syncCustomComponents(build: { customComponents?: CatalogComponent[] }): void {
  custom = new Map((build.customComponents ?? []).map(c => [c.id, c]))
}

export function componentById(id: string): CatalogComponent | undefined {
  return custom.get(id) ?? COMPONENTS.find(c => c.id === id)
}

export function isCustomComponent(id: string): boolean {
  return custom.has(id)
}
